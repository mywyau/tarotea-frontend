-- Baseline PostgreSQL schema for the Tarotea application.
-- This migration creates structure only; it never inserts application data.

create table if not exists users (
  id text primary key,
  email text not null,
  first_name text,
  last_name text,
  stripe_customer_id text,
  deleting_at timestamptz,
  deletion_requested_at timestamptz,
  deletion_status text,
  deleted_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index if not exists users_stripe_customer_id_idx
  on users (stripe_customer_id)
  where stripe_customer_id is not null;

create table if not exists entitlements (
  user_id text primary key references users (id) on delete cascade,
  plan text not null default 'free',
  subscription_status text not null default 'no_subscription',
  cancel_at_period_end boolean not null default false,
  current_period_start timestamptz,
  current_period_end timestamptz,
  canceled_at timestamptz
);

create table if not exists billing_subscriptions (
  stripe_subscription_id text primary key,
  user_id text not null references users (id) on delete cascade,
  stripe_customer_id text not null,
  plan text not null,
  subscription_status text not null,
  cancel_at_period_end boolean not null default false,
  current_period_start timestamptz,
  current_period_end timestamptz,
  canceled_at timestamptz,
  latest_invoice_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists billing_subscriptions_user_id_idx
  on billing_subscriptions (user_id);

create index if not exists billing_subscriptions_customer_id_idx
  on billing_subscriptions (stripe_customer_id);

create table if not exists stripe_events (
  event_id text primary key,
  event_type text not null,
  stripe_created_at timestamptz,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  status text not null default 'received',
  payload jsonb not null,
  stripe_subscription_id text,
  stripe_customer_id text,
  user_id text references users (id) on delete cascade,
