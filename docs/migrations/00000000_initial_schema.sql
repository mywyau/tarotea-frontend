);

create index if not exists stripe_events_user_received_idx
  on stripe_events (user_id, received_at desc);

create index if not exists stripe_events_status_idx
  on stripe_events (status);

-- The user reference becomes null during deletion so the worker can record
-- completion without retaining the deleted user's identifier.
create table if not exists account_deletion_jobs (
  id bigint generated by default as identity primary key,
  user_id text references users (id) on delete set null,
  status text not null default 'pending',
  attempt_count integer not null default 0,
  last_error text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz
);

create index if not exists account_deletion_jobs_user_created_idx
  on account_deletion_jobs (user_id, created_at desc);

create table if not exists levels (
  id bigint generated by default as identity primary key,
